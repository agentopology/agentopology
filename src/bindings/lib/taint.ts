/**
 * The scripts behind `threat-model { }` (Claude Code only).
 *
 * - taint-mark.sh, a PostToolUse hook on the untrusted tools: writes
 *   `.claude/state/taint/<session_id>` holding `{"source": ..., "ts": <epoch>}`.
 * - taint-guard.sh, a PreToolUse hook on the tools the refuse rules name: while
 *   the session's mark exists, a call that matches a refuse-after-untrusted
 *   rule exits 2 with the source in the reason. The mark ends only in a new
 *   session (a new session_id has no file), or for one act when the `lift:`
 *   human has an ok row in `.claude/state/approvals.jsonl` whose `act` is that
 *   rule string and whose `at` is not older than the mark.
 *
 * The mark folder and the approvals file are kept from the agent by
 * before-edit.sh and before-action.sh (see protectedLedgers in guards.ts).
 *
 * @module
 */

import type { TopologyAST } from "../../parser/ast.js";
import type { GeneratedFile } from "../types.js";
import { FAIL_CLOSED, FAIL_CLOSED_DONE } from "./stub.js";
import { CANON_FUNCTION, projectRootLines, shellQuote, type GuardPlatform } from "./guards.js";
import { EDIT_TOOLS, READ_TOOLS, SHELL_TOOLS, isPathGlob, splitRule, untrustedEntries } from "./threat.js";

const BT = "`";

/** Where a session's mark is, relative to the project root. */
export const taintDir = (p: GuardPlatform) => `${p.stateDir}/taint`;
/** The human ledger a lift row is read from, relative to the project root. */
export const liftLedger = (p: GuardPlatform) => `${p.stateDir}/approvals.jsonl`;

type McpTool = (t: string) => string;

const alt = (names: string[]) => [...new Set(names)].join("|");

/** The PostToolUse matcher of the mark hook: every tool that can read an untrusted input. */
export function taintMarkMatcher(ast: TopologyAST, mcpTool: McpTool): string {
  const names: string[] = [];
  for (const e of untrustedEntries(ast)) {
    if (e === "web") names.push("WebFetch", "WebSearch");
    else if (e.startsWith("mcp:")) { const m = mcpTool(`mcp.${e.slice(4)}`); names.push(`${m}__.*`, m); }
    else names.push(...READ_TOOLS);
  }
  return alt(names);
}

/** The tool names a refuse rule is checked on, as hook-matcher alternatives. */
function ruleTools(head: string, mcpTool: McpTool): string[] {
  if ((SHELL_TOOLS as readonly string[]).includes(head)) return [...SHELL_TOOLS];
  if (head === "Edit") return [...EDIT_TOOLS];
  if (head === "Read") return [...READ_TOOLS];
  const t = mcpTool(head);
  const re = t.replace(/\*/g, ".*");
  // `mcp__server` alone is every tool of the server.
  return /^mcp__[^_]+(?:_[^_]+)*$/.test(t) && !t.includes("__", 5) ? [`${re}__.*`, re] : [re];
}

/** The PreToolUse matcher of the guard hook. */
export function taintGuardMatcher(ast: TopologyAST, mcpTool: McpTool): string {
  return alt((ast.threatModel?.refuseAfterUntrusted ?? []).flatMap((r) => ruleTools(splitRule(r).head, mcpTool)));
}

const lowerGlob = (g: string) => g.replace(/^\.\//, "").replace(/\*\*+/g, "*").toLowerCase();

const jqCheck = (what: string) => [
  "if ! command -v jq >/dev/null 2>&1; then",
  `  echo "agentopology: jq is required ${what}, so this call is blocked" >&2`,
  "  exit 2",
  "fi",
];

const sessionLines = (what: string) => [
  "INPUT=$(cat)",
  `SID=$(printf '%s' "$INPUT" | jq -er '.session_id | strings') || { echo "agentopology: the hook input has no session id, so ${what}" >&2; exit 2; }`,
  `[[ $SID =~ ^[A-Za-z0-9_-]{1,128}$ ]] || { echo "agentopology: the session id is not a safe file name, so ${what}" >&2; exit 2; }`,
  `TOOL=$(printf '%s' "$INPUT" | jq -er '.tool_name | strings') || { echo "agentopology: the hook input has no tool name, so ${what}" >&2; exit 2; }`,
];

/** taint-mark.sh, or null when nothing is untrusted. */
export function generateTaintMarkScript(ast: TopologyAST, p: GuardPlatform, mcpTool: McpTool): GeneratedFile | null {
  const entries = untrustedEntries(ast);
  if (entries.length === 0) return null;
  const name = ast.topology.name;
  const globs = entries.filter((e) => e !== "web" && !e.startsWith("mcp:") && isPathGlob(e));
  const cases: string[] = [];
  if (entries.includes("web")) cases.push(`  WebFetch|WebSearch) SRC=web ;;`);
  for (const e of entries) {
    if (!e.startsWith("mcp:")) continue;
    const m = mcpTool(`mcp.${e.slice(4)}`);
    cases.push(`  ${shellQuote(m)}|${shellQuote(m + "__")}*) SRC=${shellQuote(e)} ;;`);
  }
  const lines = [
    "#!/usr/bin/env bash",
    `# After ${p.label} reads an untrusted input in topology "${name}": mark the session.`,
    `# Auto-generated by agentopology scaffold. Wired in ${p.hooksFile} as a PostToolUse hook.`,
    `# The mark is ${taintDir(p)}/<session_id>, {"source": ..., "ts": <epoch seconds>}. It ends only in a new`,
    "# session, or for one act when the person named in threat-model { lift } approves that act in the ledger.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...projectRootLines(p, name, "fallback"),
    ...jqCheck("to mark an untrusted read"),
    ...sessionLines("the read cannot be marked"),
    ...(globs.length ? CANON_FUNCTION : []),
    "SRC=''",
    'case "$TOOL" in',
    ...cases,
    ...(globs.length
      ? [
          "  Read|Grep|Glob)",
          `    P=$(printf '%s' "$INPUT" | jq -r '.tool_input | objects | (.file_path // .path // "") | strings')`,
          '    if [ -z "$P" ] && [ "$TOOL" != Read ]; then P=.; fi',
          '    if [ -n "$P" ]; then',
          '      R=$(canon "$P"); RL=$(printf \'%s\' "$R" | tr \'[:upper:]\' \'[:lower:]\')',
          ...globs.flatMap((g) => [
            `      PAT=${shellQuote(lowerGlob(g))}`,
            // A Grep or Glob over a folder reads what is in it: the folder holding the glob's start counts.
            `      if [ -z "$SRC" ] && { [[ $RL == $PAT ]] || { [ "$TOOL" != Read ] && { [ "$RL" = . ] || [[ $PAT == "$RL"/* ]]; }; }; }; then SRC=${shellQuote(g)}; fi`,
          ]),
          "    fi ;;",
        ]
      : []),
    "esac",
    'if [ -n "$SRC" ]; then',
    `  mkdir -p ${shellQuote(taintDir(p))}`,
    `  TMP=$(mktemp ${shellQuote(taintDir(p) + "/.tmp.XXXXXX")})`,
    `  jq -n --arg s "$SRC" --argjson t "$(date +%s)" '{source: $s, ts: $t}' > "$TMP"`,
    `  mv -f "$TMP" ${shellQuote(taintDir(p) + "/")}"$SID"`,
    "fi",
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  return { path: `${p.scriptsDir(name)}/taint-mark.sh`, content: lines.join("\n"), category: "script", executable: true };
}

/** taint-guard.sh, or null when there is nothing to mark or nothing to refuse. */
export function generateTaintGuardScript(ast: TopologyAST, p: GuardPlatform, mcpTool: McpTool): GeneratedFile | null {
  const rules = ast.threatModel?.refuseAfterUntrusted ?? [];
  if (untrustedEntries(ast).length === 0 || rules.length === 0) return null;
  const name = ast.topology.name;
  const lift = ast.threatModel?.lift;
  const needsShell = rules.some((r) => (SHELL_TOOLS as readonly string[]).includes(splitRule(r).head) && splitRule(r).spec !== undefined);
  const needsPath = rules.some((r) => splitRule(r).spec !== undefined && !(SHELL_TOOLS as readonly string[]).includes(splitRule(r).head));

  const dispatch: string[] = [];
  for (const rule of rules) {
    const { head, spec } = splitRule(rule);
    const sq = shellQuote(rule);
    let tool: string;
    if ((SHELL_TOOLS as readonly string[]).includes(head)) tool = '[ "$SHELLISH" = 1 ]';
    else if (head === "Edit") tool = `case "$TOOL" in ${EDIT_TOOLS.join("|")}) true ;; *) false ;; esac`;
    else if (head === "Read") tool = `case "$TOOL" in ${READ_TOOLS.join("|")}) true ;; *) false ;; esac`;
    else {
      const t = mcpTool(head);
      const wide = /^mcp__[^_]+(?:_[^_]+)*$/.test(t) && !t.includes("__", 5);
      tool = wide ? `case "$TOOL" in ${shellQuote(t)}|${shellQuote(t + "__")}*) true ;; *) false ;; esac` : `[[ $TOOL == ${t.includes("*") ? t : shellQuote(t)} ]]`;
    }
    if (spec === undefined || spec === "*" || spec === "") {
      dispatch.push(`if ${tool}; then hit ${sq}; fi`);
    } else if ((SHELL_TOOLS as readonly string[]).includes(head)) {
      const pat = spec.toLowerCase().replace(/:\*$/, " *");
      dispatch.push(`if ${tool} && shell_hit ${shellQuote(pat)}; then hit ${sq}; fi`);
    } else if (spec.startsWith("domain:")) {
      dispatch.push(`if ${tool} && domain_hit ${shellQuote(spec.slice(7).toLowerCase())}; then hit ${sq}; fi`);
    } else {
      dispatch.push(`if ${tool} && path_hit ${shellQuote(lowerGlob(spec))}; then hit ${sq}; fi`);
    }
  }

  const lines = [
    "#!/usr/bin/env bash",
    `# Before ${p.label} runs a tool of topology "${name}": refuse an act the threat model holds back`,
    "# while this session has read untrusted input.",
    `# Auto-generated by agentopology scaffold. Wired in ${p.hooksFile} as a PreToolUse hook.`,
    `# Exit 2 blocks the call and shows the reason (it names the source) to ${p.modelName}.`,
    `# The session's mark is ${taintDir(p)}/<session_id>. A new session has none.`,
    lift
      ? `# A person ends the hold for one act by adding {"step": "${lift}", "ok": true, "act": "<rule>", "at": "<ISO time>"} to ${liftLedger(p)}.`
      : "# Nothing else ends it: no lift: human is named.",
    "# Not seen: a command reached through a variable, an alias, a function or another script.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...projectRootLines(p, name, "fallback"),
    ...jqCheck("to check this call"),
    ...sessionLines("this call cannot be checked and is blocked"),
    'MARK=' + shellQuote(taintDir(p) + "/") + '"$SID"',
    'if [ ! -f "$MARK" ]; then',
    `  ${FAIL_CLOSED_DONE}`,
    "  exit 0",
    "fi",
    "# A mark that cannot be read still holds: its source is unknown and no row is newer than it.",
    `SRC=$(jq -er '.source | strings' "$MARK" 2>/dev/null) || SRC=unknown`,
    `TS=$(jq -er '.ts | numbers' "$MARK" 2>/dev/null) || TS=9999999999`,
    `LIFT=${shellQuote(lift ?? "")}`,
    `LEDGER=${shellQuote(liftLedger(p))}`,
    "# lifted ACT: the last row of the lift person for this act is ok and not older than the mark.",
    "lifted() {",
    '  [ -n "$LIFT" ] && [ -f "$LEDGER" ] || return 1',
    String.raw`  [ "$(jq -rs --arg step "$LIFT" --arg act "$1" --argjson ts "$TS" '[.[] | select(type == "object" and .step == $step and .act == $act)] | last | if . == null then false else (.ok == true and ((.at | strings | sub("\\.[0-9]+"; "") | fromdateiso8601) >= $ts)) end' "$LEDGER" 2>/dev/null)" = true ]`,
    "}",
    "hit() {",
    '  if lifted "$1"; then return 0; fi',
    '  echo "agentopology: refused ($1). This session read untrusted input ($SRC), so this act is held back." >&2',
    lift
      ? `  echo "agentopology: ${lift} can allow this act by adding a row for it to ${liftLedger(p)}; the model must not write that row, so ask the person. A new session also starts clean." >&2`
      : '  echo "agentopology: start a new session to continue; nothing lifts the hold in this one." >&2',
    "  exit 2",
    "}",
    'SHELLISH=0; case "$TOOL" in Bash|Monitor|PowerShell) SHELLISH=1 ;; esac',
    "CMD=''",
    `if [ "$SHELLISH" = 1 ]; then CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input | objects | (.command // "") | strings') || { echo "agentopology: the command could not be read, so it is blocked" >&2; exit 2; }; fi`,
    ...(needsShell
      ? [
          "# The command is cut into segments at & | ; ( ) and backticks; quotes and backslashes are dropped, letters made lower",
          "# case, spaces made single, leading VAR=value words and the program's path dropped.",
          String.raw`NSEGS=$(printf '%s' "$CMD" | tr '[:upper:]' '[:lower:]' | tr -d "\"'\\\\" | tr '&|;()${BT}' '\n\n\n\n\n\n' | tr -s ' \t' ' ' | while IFS= read -r S || [ -n "$S" ]; do`,
          '  S="${S# }"; S="${S% }"',
          "  RE='^[a-z_][a-z0-9_]*=[^ ]*[ ](.*)$'",
          '  while [[ $S =~ $RE ]]; do S=${BASH_REMATCH[1]}; done',
          '  F=${S%% *}; [ "$F" = "${F##*/}" ] || S="${F##*/}${S#"$F"}"',
          '  printf \'%s\\n\' "$S"',
          "done)",
          "# shell_hit PATTERN: a segment matches as Claude Code matches a Bash rule (a trailing ' *' also matches the bare command);",
          "# a segment run through a program that runs its arguments (eval, sh, env, sudo, xargs ...) counts when it holds the pattern's fixed start.",
          "shell_hit() {",
          "  local pat=$1 lit s first",
          "  lit=${pat%%\\**}; lit=${lit% }",
          "  while IFS= read -r s || [ -n \"$s\" ]; do",
          '    [ -n "$s" ] || continue',
          "    if [[ $s == $pat ]]; then return 0; fi",
          "    if [[ $pat == *' *' && $s == \"${pat% \\*}\" ]]; then return 0; fi",
          '    first=${s%% *}',
          '    case "$first" in eval|bash|sh|zsh|dash|env|xargs|sudo|timeout|nohup|exec|command|time|nice|watch|ssh) if [ -n "$lit" ] && [[ $s == *"$lit"* ]]; then return 0; fi ;; esac',
          '  done <<< "$NSEGS"',
          "  return 1",
          "}",
        ]
      : []),
    ...(needsPath
      ? [
          ...CANON_FUNCTION,
          `SUBJ=$(printf '%s' "$INPUT" | jq -r '.tool_input | objects | (.file_path // .notebook_path // .path // .url // "") | strings')`,
          "# path_hit PATTERN: the file the call names, made project-relative, matches. A call that names none is a hit.",
          "path_hit() {",
          '  [ -n "$SUBJ" ] || return 0',
          '  local r; r=$(canon "$SUBJ"); r=$(printf \'%s\' "$r" | tr \'[:upper:]\' \'[:lower:]\')',
          "  [[ $r == $1 ]]",
          "}",
          "# domain_hit DOMAIN: the url's host is the domain or a subdomain. A call with no readable host is a hit.",
          "domain_hit() {",
          "  local h; h=$(printf '%s' \"$SUBJ\" | sed -E 's#^[A-Za-z][A-Za-z0-9+.-]*://([^/:?#]+).*#\\1#' | tr '[:upper:]' '[:lower:]')",
          '  [ -n "$h" ] && [ "$h" != "$(printf \'%s\' "$SUBJ" | tr \'[:upper:]\' \'[:lower:]\')" ] || return 0',
          '  [[ $h == "$1" || $h == *".$1" ]]',
          "}",
        ]
      : []),
    ...dispatch,
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  return { path: `${p.scriptsDir(name)}/taint-guard.sh`, content: lines.join("\n"), category: "script", executable: true };
}
