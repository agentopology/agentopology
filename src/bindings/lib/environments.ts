/**
 * `environments { }` compile: one `env/<name>.env` file per environment, and
 * the names sessions.md uses for its AT_ENV start-line variants.
 *
 * A key is upper-cased with "-" turned into "_". A value whose key holds
 * TOKEN, KEY, SECRET or PASSWORD is not written: a comment says to set it
 * outside the repo.
 *
 * @module
 */

import type { TopologyAST } from "../../parser/ast.js";
import type { GeneratedFile } from "../types.js";

const SAFE_ENV_NAME = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;
const SECRET_KEY = /TOKEN|KEY|SECRET|PASSWORD/;
const PLAIN_VALUE = /^[A-Za-z0-9_./:@%+=,-]*$/;

export function envVarName(key: string): string {
  return key.toUpperCase().replace(/-/g, "_");
}

/** The environments that are safe to name in a path or a shell line, in source order. */
export function environmentNames(ast: TopologyAST): string[] {
  return Object.keys(ast.environments ?? {}).filter((n) => SAFE_ENV_NAME.test(n));
}

function envValue(value: string | number): string {
  const s = String(value);
  if (PLAIN_VALUE.test(s)) return s;
  return `"${s.replace(/[\\"$`]/g, "\\$&").replace(/\n/g, "\\n")}"`;
}

export function generateEnvironmentFiles(ast: TopologyAST): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const [name, values] of Object.entries(ast.environments ?? {})) {
    if (!SAFE_ENV_NAME.test(name)) {
      console.warn(`[claude-code] env/${name}.env not written: an environment name may hold only letters, digits, "-" and "_"`);
      continue;
    }
    const lines = [`# Environment "${name}". Auto-generated by agentopology scaffold.`];
    for (const [key, value] of Object.entries(values)) {
      if (typeof value !== "string" && typeof value !== "number") continue; // V137 reports it
      const varName = envVarName(key);
      if (SECRET_KEY.test(varName)) lines.push(`# ${varName}: set outside the repo (not written here)`);
      else lines.push(`${varName}=${envValue(value)}`);
    }
    lines.push("");
    files.push({ path: `env/${name}.env`, content: lines.join("\n"), category: "machine" });
  }
  return files;
}
