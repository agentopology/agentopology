/**
 * Per-agent walls: the read guard for `never-reads` (on an agent) and `secrets` (top level).
 *
 * One PreToolUse hook on Read|Grep|Glob|Bash. Claude Code puts `agent_type` in the hook input when the
 * call comes from a subagent, or from a session started with `--agent`; it is absent in the plain main
 * session (https://code.claude.com/docs/en/hooks, "Common input fields"). So:
 *
 * - an agent's `never-reads` globs are refused for that agent only;
 * - a secret's path is refused to every agent that is not a reader, and to the main session (no
 *   agent_type) unless "main" is a reader.
 *
 * The paths a call names are read from the tool's input (Read `file_path`; Grep `path` and `glob`; Glob
 * `path` and `pattern`), and for Bash from the words of the command, read the way the other guards read
 * a command (the `norm` function: quotes and backslashes dropped). A path is made absolute, with `.` and
 * `..` resolved, then relative to the project root, and compared lower case with each glob.
 *
 * What a Bash read can hide (not seen): a path built in a variable or by command substitution
 * (`cat $(echo .e)nv`, `p=.env; cat $p`), a path reached after `cd` (`cd private && cat notes`), a path
 * a script or program opens on its own (`python app.py` that reads `.env`), a directory search that
 * walks into the protected folder from above (`grep -r key .`), an encoded or split name. A word that
 * holds a glob character is compared as written, so `cat priv[a-z]*` is not matched against
 * `private/**`.
 *
 * @module
 */

import type { AgentNode, TopologyAST } from "../../parser/ast.js";
import type { GeneratedFile } from "../types.js";
import { FAIL_CLOSED, FAIL_CLOSED_DONE } from "./stub.js";
import { CANON_FUNCTION, JQ_AGENT_NORM, MATCH_FUNCTIONS, noJqLines, shellQuote, type GuardPlatform } from "./guards.js";

/** One wall: a glob, who it applies to, and what to call it in the refusal. */
export interface Wall {
  /** The glob as the author wrote it. */
  path: string;
  /** The glob as a lower-case shell pattern (see {@link wallPattern}). */
  pattern: string;
  kind: "never-reads" | "secret";
  /** never-reads: the one agent it binds. secret: the secret's id. */
  owner: string;
  /** secret only: the agents (and "main") that may read it. */
  readers: string[];
}

/**
 * A path glob as a bash `[[ == ]]` pattern: `**` is `*` (which already crosses `/`), `**` + `/` is `*`, a
 * leading `./` or `/` is dropped, a trailing `/` means everything below. Lower case.
 */
export function wallPattern(glob: string): string {
  let g = glob.trim().replace(/^\.\//, "").replace(/^\/+/, "");
  g = g.replace(/\*\*\/?/g, "*");
  if (g.endsWith("/")) g += "*";
  return g.replace(/\*{2,}/g, "*").toLowerCase();
}

/** Every wall the topology declares, in source order. */
export function wallsOf(ast: TopologyAST): Wall[] {
  const walls: Wall[] = [];
  for (const n of ast.nodes) {
    if (n.type !== "agent") continue;
    for (const g of (n as AgentNode).neverReads ?? []) {
      if (g.trim()) walls.push({ path: g, pattern: wallPattern(g), kind: "never-reads", owner: n.id, readers: [] });
    }
  }
  for (const s of ast.secrets ?? []) {
    if (s.path && s.path.trim()) walls.push({ path: s.path, pattern: wallPattern(s.path), kind: "secret", owner: s.id, readers: s.readers.map((r) => r.toLowerCase()) });
  }
  return walls;
}

/** The longest run of plain characters in a glob: what the no-jq reading looks for. */
function literalOf(glob: string): string {
  const runs = glob.split(/[*?[\]{}]+/).map((r) => r.replace(/[^A-Za-z0-9]/g, "")).filter(Boolean);
  return runs.sort((a, b) => b.length - a.length)[0] ?? "";
}

/**
 * before-read.sh (null when the topology declares no wall). Exit 2 refuses the call and puts the reason
 * on stderr. Input it cannot read blocks. Without jq, a payload holding the letters of a wall's longest
 * plain part is refused; any other runs, with a line on stderr.
 */
export function generateBeforeReadScript(ast: TopologyAST, p: GuardPlatform): GeneratedFile | null {
  const walls = wallsOf(ast);
  if (walls.length === 0) return null;
  const name = ast.topology.name;
  const v = p.projectDirVar;
  const lines = [
    "#!/usr/bin/env bash",
    `# Before ${p.label} reads a path in a project of topology "${name}": per-agent walls.`,
    `# Auto-generated by agentopology scaffold. Wired in ${p.hooksFile} as a PreToolUse hook on`,
    "# Read|Grep|Glob|Bash. An agent's never-reads paths, and a secret's path for an agent that is not a",
    `# reader (the main session counts as "main"), are refused (exit 2, the reason on stderr to ${p.modelName}).`,
    "# The calling agent is agent_type in the hook input; the main session sends none.",
    "# Not seen in a Bash command: a path built in a variable or substitution, one reached after cd, one a",
    "# script opens itself, a search from a folder above the protected one. Input it cannot read blocks too.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...(v === null
      ? [`ROOT="$(cd "$(dirname "\${BASH_SOURCE[0]}")/${p.scriptsDir(name).split("/").map(() => "..").join("/")}" && pwd)"`]
      : [
          `if [ -z "\${${v}:-}" ]; then echo "agentopology: ${v} is not set, so this read cannot be checked and is blocked" >&2; exit 2; fi`,
          `ROOT="$(cd "$${v}" && pwd)"`,
        ]),
    ...noJqLines({
      refuse: "agentopology: jq is required to check this read, so it is blocked",
      pass: "agentopology: jq is not installed; this call names no walled path, so it runs. Install jq to check reads.",
      inOrder: walls.map((w) => [literalOf(w.path)]).filter((l) => l[0]),
    }),
    "INPUT=$(cat)",
    '[ -n "$INPUT" ] || { echo "agentopology: the hook input is empty, so the read is blocked" >&2; exit 2; }',
    "TOOL=$(printf '%s' \"$INPUT\" | jq -er '.tool_name | strings') || { echo \"agentopology: the hook input is not valid JSON, so the read is blocked\" >&2; exit 2; }",
    // No agent_type: the main session. A value that is not a string blocks.
    `AGENT=$(printf '%s' "$INPUT" | jq -er '(.agent_type // "") | strings | ${JQ_AGENT_NORM}') || { echo "agentopology: the agent name could not be read, so the read is blocked" >&2; exit 2; }`,
    '[ -n "$AGENT" ] || AGENT=main',
    ...MATCH_FUNCTIONS,
    "set -f",
    "# The paths the call names, one per line.",
    'case "$TOOL" in',
    "  Bash|Monitor|PowerShell)",
    "    CMD=$(printf '%s' \"$INPUT\" | jq -er '.tool_input | objects | (.command // \"\") | strings') || { echo \"agentopology: no command could be read, so it is blocked\" >&2; exit 2; }",
    "    CMD=${CMD//$'\\\\\\n'/}",
    "    ;;",
    "  *)",
    "    CMD=''",
    "    ;;",
    "esac",
  ];
  lines.push(
    "# Paths from the tool's own fields: Read file_path; Grep path and glob; Glob path, pattern, and both joined.",
    "if [ -z \"$CMD\" ]; then",
    "  PATHS=$(printf '%s' \"$INPUT\" | jq -r --arg tool \"$TOOL\" '.tool_input | objects | [.file_path, .notebook_path, .path, .glob, (if $tool == \"Glob\" then (.pattern, (if .path then (.path + \"/\" + .pattern) else empty end)) else empty end)] | .[] | strings') || { echo \"agentopology: no path could be read, so the call is blocked\" >&2; exit 2; }",
    "else",
    "  PATHS=$(printf '%s\\n' \"$(norm \"$CMD\")\" | tr ';&|()<>=:,' '\\n' | tr ' ' '\\n')",
    "fi",
    ...CANON_FUNCTION,
    "CANDS=''",
    "while IFS= read -r P || [ -n \"$P\" ]; do",
    '  [ -n "$P" ] || continue',
    '  R="$(canon "$P")"',
    "  CANDS=\"$CANDS$(lower \"$R\")\"$'\\n'",
    'done <<< "$PATHS"',
    "# hit PATTERN: a candidate equals it, is the folder above it (so `private` meets `private/*`), or, for a pattern",
    "# with no slash, has that file name.",
    "hit() {",
    "  local c",
    "  while IFS= read -r c || [ -n \"$c\" ]; do",
    '    [ -n "$c" ] || continue',
    '    if [[ $c == $1 || "$c/" == $1 ]] || { [[ $1 != */* ]] && [[ ${c##*/} == $1 ]]; }; then HIT=$c; return 0; fi',
    "  done <<< \"$CANDS\"",
    "  return 1",
    "}",
    "HIT=''",
  );
  for (const w of walls) {
    if (w.kind === "never-reads") {
      lines.push(
        `if [ "$AGENT" = ${shellQuote(w.owner.toLowerCase())} ] && hit ${shellQuote(w.pattern)}; then echo "agentopology: agent ${w.owner} must not read ${w.path} (never-reads); refused: $HIT" >&2; exit 2; fi`,
      );
    } else {
      const list = ` ${w.readers.join(" ")} `;
      lines.push(
        `case ${shellQuote(list)} in *" $AGENT "*) ;; *) if hit ${shellQuote(w.pattern)}; then echo "agentopology: secret ${w.owner} (${w.path}) is for ${w.readers.length ? w.readers.join(", ") : "no one"} only; $AGENT may not read it; refused: $HIT" >&2; exit 2; fi ;; esac`,
      );
    }
  }
  lines.push(FAIL_CLOSED_DONE, "exit 0", "");
  return { path: `${p.scriptsDir(name)}/before-read.sh`, content: lines.join("\n"), category: "script", executable: true };
}
