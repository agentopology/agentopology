/**
 * Records on Claude Code: what a record with fields compiles to.
 *
 * - `record-<id>.sh <json>`: appends a row to the record's file only when it
 *   holds every declared field with the declared type; otherwise exit 2 naming
 *   the field and nothing is written. It adds `ts` when missing. A row
 *   `{ok: "n/a", reason}` is written through it, and `reason` is required.
 * - `after-action.sh`: a PostToolUse hook on Bash. When a step's command ran
 *   and Claude Code reports it succeeded, it appends the step's ledger row
 *   `{step, ok: true, ts, model}`. It reads the command with the same shell
 *   functions before-action.sh does (MATCH_FUNCTIONS), so both see the same
 *   step in the same command.
 * - `.claude/records.json`: every record, with the gates that read it.
 *
 * PostToolUse fires only for a tool call that succeeded; a Bash command that
 * exits non-zero fires PostToolUseFailure, whose `error` starts `Exit code N`
 * (https://code.claude.com/docs/en/hooks). The hook is wired on PostToolUse
 * only, and also skips a payload that carries `error`, an interrupt, or a
 * `tool_response` that reads `Exit code N` with N not 0.
 */

import type { ActionNode, GateNode, RecordDef, TopologyAST } from "../../parser/ast.js";
import { gateAnchors, recordFields } from "../../parser/ast.js";
import { gateLedger } from "../../parser/ledger.js";
import type { GeneratedFile } from "../types.js";
import {
  GUARD_OPTIONS, MATCH_FUNCTIONS, RESOLVE_FUNCTIONS, checkableActionGate, projectRootLines, shellQuote, stepKey,
  type GuardPlatform,
} from "./guards.js";

/** The ISO 8601 time a `ts` field must hold, as a jq regex (passed with --arg, so the backslash is raw). */
const TS_RE = "^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\\.[0-9]+)?(Z|[+-][0-9]{2}:[0-9]{2})$";

/** True when the record opted into the writer script: it declares fields, a schema, a writer or a kind. */
export function recordIsTyped(r: RecordDef): boolean {
  return !!(r.fields || r.schema || r.writer || r.kind);
}

/** The gates that read a record: before-action.sh checks its ledger before a script step. */
export function recordReaders(ast: TopologyAST, r: RecordDef): GateNode[] {
  return ast.nodes
    .filter((n): n is GateNode => n.type === "gate")
    .filter((g) => checkableActionGate(ast, g) && gateLedger(ast, g)?.id === r.id);
}

/** `<scripts>/record-<id>.sh <json>`, one per record that declares fields, a schema, a writer or a kind. */
export function generateRecordScripts(ast: TopologyAST, p: GuardPlatform): GeneratedFile[] {
  const name = ast.topology.name;
  return (ast.records ?? []).filter(recordIsTyped).map((r) => {
    const fields = recordFields(r);
    const lines = [
      "#!/usr/bin/env bash",
      `# Appends one row to the record "${r.id}" (${r.path}) of topology "${name}".`,
      `# Auto-generated by agentopology scaffold. Usage: record-${r.id}.sh '<json object>'`,
      `# The row must hold every declared field with its type: ${fields.map((f) => `${f.name}: ${f.type}`).join(", ") || "(none declared)"}.`,
      "# A row missing a field, or holding one of the wrong type, exits 2 naming the field and writes nothing.",
      "# ts is added when missing. A row with ok: \"n/a\" must give a non-empty reason.",
      "set -euo pipefail",
      ...projectRootLines(p, name, "fallback"),
      `fail() { echo "agentopology: record ${r.id}: $1; nothing was written" >&2; exit 2; }`,
      "command -v jq >/dev/null 2>&1 || fail \"jq is required to check the row\"",
      "ROW=${1-}",
      `[ -n "$ROW" ] || fail "usage: record-${r.id}.sh '<json object>'"`,
      "printf '%s' \"$ROW\" | jq -e 'type == \"object\"' >/dev/null 2>&1 || fail \"the row is not a JSON object\"",
      "# ts is added when missing",
      "ROW=$(printf '%s' \"$ROW\" | jq -c --arg ts \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\" 'if has(\"ts\") then . else . + {ts: $ts} end')",
      "# ok: \"n/a\" says the step did not apply; it must say why",
      "printf '%s' \"$ROW\" | jq -e 'if .ok == \"n/a\" then (.reason | type == \"string\" and length > 0) else true end' >/dev/null 2>&1 \\",
      "  || fail \"the field reason is required when ok is \\\"n/a\\\"\"",
      "# check_field NAME TYPE: the row holds NAME, of TYPE",
      "check_field() {",
      "  local got",
      `  got=$(printf '%s' "$ROW" | jq -r --arg f "$1" --arg t "$2" --arg re ${shellQuote(TS_RE)} '`,
      "    if has($f) | not then \"missing\"",
      "    elif $t == \"string\" then (if (.[$f] | type) == \"string\" then \"ok\" else \"wrong\" end)",
      "    elif $t == \"number\" then (if (.[$f] | type) == \"number\" then \"ok\" else \"wrong\" end)",
      "    elif $t == \"boolean\" then (if (.[$f] | type) == \"boolean\" or ($f == \"ok\" and .[$f] == \"n/a\") then \"ok\" else \"wrong\" end)",
      "    elif $t == \"ts\" then (if (.[$f] | type) == \"string\" and (.[$f] | test($re)) then \"ok\" else \"wrong\" end)",
      "    else \"wrong\" end')",
      "  case $got in",
      "    ok) ;;",
      "    missing) fail \"the row has no field $1 (type $2)\" ;;",
      "    *) fail \"the field $1 must be of type $2\" ;;",
      "  esac",
      "}",
      ...fields.map((f) => `check_field ${shellQuote(f.name)} ${shellQuote(f.type)}`),
      `TMPL=${shellQuote(r.path.replace(/^\.\//, ""))}`,
      "if [[ \"$TMPL\" == *\"{unit}\"* ]]; then",
      "  UNIT=$(printf '%s' \"$ROW\" | jq -r 'if (.unit | type) == \"string\" then .unit else \"\" end')",
      "  [ -n \"$UNIT\" ] || fail \"the path $TMPL has {unit}, so the row must give a unit\"",
      "  if ! [[ \"$UNIT\" =~ ^[A-Za-z0-9_.@+-]+$ ]] || [[ \"$UNIT\" == *..* ]]; then fail \"the unit \\\"$UNIT\\\" is not a safe file name\"; fi",
      "  FILE=\"${TMPL//\\{unit\\}/$UNIT}\"",
      "else",
      "  FILE=\"$TMPL\"",
      "fi",
      "mkdir -p \"$(dirname \"$FILE\")\"",
      "printf '%s\\n' \"$ROW\" >> \"$FILE\"",
      "",
    ];
    return { path: `${p.scriptsDir(name)}/record-${r.id}.sh`, content: lines.join("\n"), category: "script" as const, executable: true };
  });
}

/** The steps after-action.sh writes a row for: an action with commands that a typed ledger's gate stands after. */
export function recordedSteps(ast: TopologyAST): Array<{ action: ActionNode; record: RecordDef }> {
  const out = new Map<string, { action: ActionNode; record: RecordDef }>();
  for (const node of ast.nodes) {
    if (node.type !== "gate") continue;
    const gate = node as GateNode;
    const record = gateLedger(ast, gate);
    if (!record || !recordIsTyped(record)) continue;
    for (const id of gateAnchors(gate, "after")) {
      const action = ast.nodes.find((n) => n.id === id);
      if (action?.type !== "action" || !(action as ActionNode).commands?.length) continue;
      if (!out.has(id)) out.set(id, { action: action as ActionNode, record });
    }
  }
  return [...out.values()];
}

/**
 * after-action.sh: the PostToolUse hook on Bash that appends a step's ledger row when its command
 * succeeded. Null when no step is recorded. It reads the command with MATCH_FUNCTIONS, the functions
 * before-action.sh reads it with.
 */
export function generateAfterActionScript(ast: TopologyAST, p: GuardPlatform): GeneratedFile | null {
  const steps = recordedSteps(ast);
  if (steps.length === 0) return null;
  const name = ast.topology.name;
  const sq = shellQuote;
  const gitSteps = [...new Set(ast.nodes.flatMap((n) => (n.type === "action" ? (n as ActionNode).commands ?? [] : []))
    .map(stepKey).filter((k) => k.key === "git").map((k) => k.rest.split(" ")[0]).filter(Boolean))];
  const resolve = GUARD_OPTIONS.resolveLeadingAssignments;
  const lines = [
    "#!/usr/bin/env bash",
    `# After ${p.label} ran a command, appends the ledger row of the script step it ran, for topology "${name}".`,
    `# Auto-generated by agentopology scaffold. Wired in ${p.hooksFile} as a PostToolUse hook on Bash.`,
    "# PostToolUse fires only for a call that succeeded; a command that exits non-zero fires PostToolUseFailure,",
    "# which this hook is not wired to. A payload that carries an error, an interrupt or an \"Exit code N\" (N not 0) is skipped too.",
    "# The row is {\"step\": \"<id>\", \"ok\": true, \"ts\": \"<ISO time>\", \"model\": \"<model>\"} (and the unit when the step has one).",
    "# The command is read with the functions before-action.sh reads it with. Nothing is written when the command is cut",
    "# with ; | or & (its exit status is then the last part's, not the step's), holds a command substitution, or the step",
    "# cannot be read plainly.",
    "set -u",
    ...projectRootLines(p, name, "fallback"),
    "command -v jq >/dev/null 2>&1 || { echo \"agentopology: jq is not installed, so the step's ledger row was not written\" >&2; exit 0; }",
    "INPUT=$(cat)",
    "CMD=$(printf '%s' \"$INPUT\" | jq -er '.tool_input.command // \"\"') || exit 0",
    "[ -n \"$CMD\" ] || exit 0",
    "FAILED=$(printf '%s' \"$INPUT\" | jq -r 'if (.error != null) or .hook_event_name == \"PostToolUseFailure\" or (.tool_response | type == \"object\" and .interrupted == true) then \"yes\"",
    "  elif (.tool_response | type) == \"string\" then (if (.tool_response | test(\"^Exit code [1-9]\")) then \"yes\" else \"no\" end)",
    "  elif (.tool_response | type) == \"object\" then (if ((.tool_response.exit_code // .tool_response.exitCode // 0) != 0) then \"yes\" else \"no\" end)",
    "  else \"no\" end' 2>/dev/null) || exit 0",
    "[ \"$FAILED\" = no ] || exit 0",
    "MODEL=$(printf '%s' \"$INPUT\" | jq -r '.model // \"\"' 2>/dev/null) || MODEL=''",
    "[ -n \"$MODEL\" ] || MODEL=${ANTHROPIC_MODEL:-}",
    "",
    ...MATCH_FUNCTIONS,
    ...(resolve ? RESOLVE_FUNCTIONS : []),
    `AT_GIT_STEPS=${sq(gitSteps.join(" "))}`,
    "CMD=${CMD//$'\\\\\\n'/}",
    "CMD_L=$(letters \"$CMD\")",
    "[[ $CMD == *'$('* || $CMD == *'`'* ]] && exit 0",
    "set -f",
    "# the exit status Claude Code saw is the whole command's: only a plain && chain says every part succeeded",
    "CHAIN=$(strip_redir \"$CMD\")",
    "CHAIN=${CHAIN//&&/ }",
    "case $CHAIN in *[';|&']*|*$'\\n'*) exit 0 ;; esac",
    ...(!resolve ? ['SEGS=$(strip_redir "$CMD")'] : ['SEGS=$(strip_redir "$(at_resolve "$CMD")")']),
    "for sep in '&' '|' ';' '(' ')' '`'; do SEGS=${SEGS//\"$sep\"/$'\\n'}; done",
    "TS=$(date -u +%Y-%m-%dT%H:%M:%SZ)",
    "# row STEP FILE UNIT: appends the step's ledger row",
    "row() {",
    "  mkdir -p \"$(dirname \"$2\")\"",
    "  jq -nc --arg step \"$1\" --arg unit \"$3\" --arg ts \"$TS\" --arg model \"$MODEL\" '{step: $step} + (if $unit == \"\" then {} else {unit: $unit} end) + {ok: true, ts: $ts, model: $model}' >> \"$2\"",
    "}",
    "",
  ];
  for (const { action, record } of steps) {
    const keys = [...new Map((action.commands ?? []).map((c) => { const k = stepKey(c); return [`${k.key} ${k.rest}`, k]; })).values()];
    const tmpl = record.path.replace(/^\.\//, "");
    lines.push(`# step ${action.id}, recorded in ${record.id}`);
    lines.push("while IFS= read -r -u 3 C || [ -n \"$C\" ]; do", '  C=$(norm "$C")', '  [ "$C" != "  " ] || continue', '  L=$(lower "$C")');
    lines.push("  SEG_DOUBT=0; T=0");
    for (const k of keys) lines.push(`  seg_steps "$L" ${sq(k.key)} ${sq(k.rest)}; T=$((T + SEG_N))`);
    lines.push('  [ "$T" -gt 0 ] && [ "$SEG_DOUBT" = 0 ] || continue');
    lines.push(`  TMPL=${sq(tmpl)}`);
    if (action.unitFrom) {
      lines.push(
        `  UNIT=$(jq -nr --arg c "$C" --arg re ${sq(action.unitFrom)} '[$c | match($re; "g") | .captures[0].string // ""] | .[0] // ""' 2>/dev/null) || continue`,
        '  [[ "$UNIT" =~ ^[A-Za-z0-9_.@+-]+$ ]] && [[ "$UNIT" != *..* ]] || continue',
      );
    } else {
      lines.push("  UNIT=''");
    }
    lines.push(
      '  if [[ "$TMPL" == *"{unit}"* ]]; then [ -n "$UNIT" ] || continue; FILE="${TMPL//\\{unit\\}/$UNIT}"; else FILE="$TMPL"; fi',
      `  row ${sq(action.id)} "$FILE" "$UNIT"`,
      "  break",
      'done 3<<< "$SEGS"',
      "",
    );
  }
  lines.push("exit 0", "");
  return { path: `${p.scriptsDir(name)}/after-action.sh`, content: lines.join("\n"), category: "script", executable: true };
}

/** `.claude/records.json`: every record, whether or not a gate reads it. Null when the topology has none. */
export function generateRecordsJson(ast: TopologyAST): GeneratedFile | null {
  const records = ast.records ?? [];
  if (records.length === 0) return null;
  const doc = {
    topology: ast.topology.name,
    records: records.map((r) => ({
      id: r.id,
      path: r.path,
      ...(r.kind ? { kind: r.kind } : {}),
      fields: recordFields(r).map((f) => ({ name: f.name, type: f.type })),
      ...(r.schema ? { schema: r.schema } : {}),
      ...(r.writer ? { writer: r.writer } : {}),
      readBy: recordReaders(ast, r).map((g) => g.id),
    })),
  };
  return { path: ".claude/records.json", content: JSON.stringify(doc, null, 2) + "\n", category: "machine" };
}
