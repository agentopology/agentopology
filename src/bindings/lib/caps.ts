/**
 * Caps that stop (Claude Code): `max-subagents` and `timeout` on an agent.
 *
 * Three scripts, all reading one log, `.claude/state/subagents.jsonl`:
 *
 * - caps-log.sh (SubagentStart and SubagentStop hooks) appends one line per
 *   event: the event, session_id, agent_id, agent_type and the time.
 * - max-subagents.sh (PreToolUse on Agent|Task) refuses a launch when the
 *   agent that is launching already has its cap of subagents open in that
 *   session (a SubagentStart with no SubagentStop after it).
 * - <agent>-timeout.sh (PreToolUse in the agent's own frontmatter) refuses
 *   every tool call once the agent has run longer than its timeout, counted
 *   from its SubagentStart.
 *
 * `max-cost` is not here: a hook payload carries no spend, so it is only
 * written to the metering output and validate says so (V137).
 *
 * The logger never blocks: an exit 2 on SubagentStop would keep the subagent
 * from finishing. The two guards fail closed, like the other guards.
 *
 * @module
 */

import type { AgentNode, TopologyAST } from "../../parser/ast.js";
import type { GeneratedFile } from "../types.js";
import { durationSeconds, getDelegationMode, runsAsSkill, shellQuote } from "./guards.js";
import { FAIL_CLOSED, FAIL_CLOSED_DONE } from "./stub.js";
import { isWorkflowSeamAgent } from "./seam.js";

const LOG = ".claude/state/subagents.jsonl";

// Agents written as subagents: not a workflow-rung agent, not a skill (runs: inline or fork).
const agentsOf = (ast: TopologyAST): AgentNode[] =>
  ast.nodes.filter((n): n is AgentNode => n.type === "agent" && !isWorkflowSeamAgent(n as AgentNode) && !runsAsSkill(n as AgentNode));

/** Agents with a max-subagents cap. Inline delegation starts no subagents, so none. */
export function cappedAgents(ast: TopologyAST): AgentNode[] {
  if (getDelegationMode(ast) === "inline") return [];
  return agentsOf(ast).filter((a) => a.maxSubagents !== undefined);
}

/** Agents with a timeout the hook can count (a valid duration). */
export function timedAgents(ast: TopologyAST): AgentNode[] {
  if (getDelegationMode(ast) === "inline") return [];
  return agentsOf(ast).filter((a) => durationSeconds(a.timeout) !== null);
}

/** True when any cap needs the subagent log. */
export function hasCaps(ast: TopologyAST): boolean {
  return cappedAgents(ast).length > 0 || timedAgents(ast).length > 0;
}

const dir = (name: string) => `.claude/skills/${name}/scripts`;

const NEED_JQ = [
  'command -v jq >/dev/null 2>&1 || { echo "agentopology: jq is required to check this cap, so the call is blocked. Install jq." >&2; exit 2; }',
];

const ROOT = [
  'if [ -z "${CLAUDE_PROJECT_DIR:-}" ]; then echo "agentopology: CLAUDE_PROJECT_DIR is not set, so this cap cannot be checked and the call is blocked" >&2; exit 2; fi',
  'cd "$CLAUDE_PROJECT_DIR"',
];

function loggerScript(name: string): GeneratedFile {
  const lines = [
    "#!/usr/bin/env bash",
    `# Subagent log for topology "${name}": one line per SubagentStart and SubagentStop,`,
    "# which max-subagents and timeout read. Auto-generated by agentopology scaffold.",
    "# It never blocks (exit 0): a block on SubagentStop would keep the subagent from finishing.",
    "# Without jq, or on a payload it cannot read, it writes nothing and says so.",
    "set -u",
    '[ -n "${CLAUDE_PROJECT_DIR:-}" ] && cd "$CLAUDE_PROJECT_DIR" 2>/dev/null',
    "INPUT=$(cat)",
    'command -v jq >/dev/null 2>&1 || { echo "agentopology: jq is not installed, so the subagent log is not written and caps cannot count" >&2; exit 0; }',
    `LINE=$(printf '%s' "$INPUT" | jq -ec --argjson ts "$(date +%s)" '{event: (.hook_event_name // ""), session_id: (.session_id // ""), agent_id: (.agent_id // ""), agent_type: (.agent_type // ""), ts: $ts}') || { echo "agentopology: the hook input is not valid JSON, so the subagent log is not written" >&2; exit 0; }`,
    `if [ -L .claude/state ] || [ -L ${LOG} ]; then echo "agentopology: ${LOG} or its folder is a symlink; not writing the log" >&2; exit 0; fi`,
    `mkdir -p .claude/state && printf '%s\\n' "$LINE" >> ${LOG}`,
    "exit 0",
    "",
  ];
  return { path: `${dir(name)}/caps-log.sh`, content: lines.join("\n"), category: "script", executable: true };
}

function maxSubagentsScript(name: string, agents: AgentNode[]): GeneratedFile {
  const cases = agents.flatMap((a) => [
    `  ${a.id.toLowerCase()})`,
    `    CAP=${a.maxSubagents}`,
    `    WHO=${shellQuote(a.id)}`,
    "    ;;",
  ]);
  const lines = [
    "#!/usr/bin/env bash",
    `# max-subagents for topology "${name}": refuses a subagent launch when the launching`,
    "# agent already has its cap of subagents open in this session (started, not yet stopped).",
    "# Auto-generated by agentopology scaffold. PreToolUse hook on Agent|Task; exit 2 blocks.",
    "# Open subagents are counted per session, from the log caps-log.sh writes. A subagent",
    "# whose stop was never logged stays counted as open.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...ROOT,
    ...NEED_JQ,
    "INPUT=$(cat)",
    `FROM=$(printf '%s' "$INPUT" | jq -er '(.agent_type // "") | strings | ascii_downcase') || { echo "agentopology: the hook input is not valid JSON, so the launch is blocked" >&2; exit 2; }`,
    `SESSION=$(printf '%s' "$INPUT" | jq -er '.session_id | strings') || { echo "agentopology: the hook input has no session_id, so the launch is blocked" >&2; exit 2; }`,
    "CAP=''",
    "WHO=''",
    'case "$FROM" in',
    ...cases,
    "esac",
    'if [ -z "$CAP" ]; then AT_DONE=1; exit 0; fi',
    "OPEN=0",
    `if [ -f ${LOG} ]; then`,
    `  OPEN=$(jq -rs --arg s "$SESSION" '[.[] | select(.session_id == $s and .agent_id != "")] | reduce .[] as $e ({}; .[$e.agent_id] = $e.event) | [.[] | select(. == "SubagentStart")] | length' ${LOG})`,
    "fi",
    'if [ "$OPEN" -ge "$CAP" ]; then',
    '  echo "agentopology: max-subagents: $WHO may have $CAP subagents open at once and has $OPEN, so this launch is refused. Wait for one to finish." >&2',
    "  exit 2",
    "fi",
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  return { path: `${dir(name)}/max-subagents.sh`, content: lines.join("\n"), category: "script", executable: true };
}

function timeoutScript(name: string, agent: AgentNode): GeneratedFile {
  const secs = durationSeconds(agent.timeout)!;
  const lines = [
    "#!/usr/bin/env bash",
    `# timeout for agent "${agent.id}" (topology "${name}"): refuses every tool call once the agent`,
    `# has run longer than ${agent.timeout} since its SubagentStart. Auto-generated by agentopology scaffold.`,
    "# PreToolUse hook in the agent's own frontmatter; exit 2 blocks. A call with no logged start",
    "# (the main session, or a run caps-log.sh did not see) is let through.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...ROOT,
    ...NEED_JQ,
    "INPUT=$(cat)",
    `AID=$(printf '%s' "$INPUT" | jq -er '(.agent_id // "") | strings') || { echo "agentopology: the hook input is not valid JSON, so the call is blocked" >&2; exit 2; }`,
    'if [ -z "$AID" ] || [ ! -f ' + LOG + " ]; then AT_DONE=1; exit 0; fi",
    `START=$(jq -rs --arg a "$AID" '[.[] | select(.event == "SubagentStart" and .agent_id == $a)] | last | .ts // empty' ${LOG})`,
    'if [ -z "$START" ]; then AT_DONE=1; exit 0; fi',
    "NOW=$(date +%s)",
    "ELAPSED=$((NOW - START))",
    `if [ "$ELAPSED" -gt ${secs} ]; then`,
    `  echo "agentopology: timeout: ${agent.id} ran past its timeout of ${agent.timeout} (\${ELAPSED}s since it started), so this tool call is refused. Stop and report what you have." >&2`,
    "  exit 2",
    "fi",
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  return { path: `${dir(name)}/${agent.id}-timeout.sh`, content: lines.join("\n"), category: "script", executable: true };
}

/** Every script the caps need: the logger, max-subagents.sh, one timeout script per timed agent. */
export function generateCapsScripts(ast: TopologyAST): GeneratedFile[] {
  if (!hasCaps(ast)) return [];
  const name = ast.topology.name;
  const files = [loggerScript(name)];
  const capped = cappedAgents(ast);
  if (capped.length > 0) files.push(maxSubagentsScript(name, capped));
  for (const a of timedAgents(ast)) files.push(timeoutScript(name, a));
  return files;
}

/** The settings.json hook entries for the caps, grouped by event. */
export function capsSettingsHooks(ast: TopologyAST, command: (file: string) => string): Record<string, unknown[]> {
  if (!hasCaps(ast)) return {};
  const out: Record<string, unknown[]> = {
    SubagentStart: [{ hooks: [{ type: "command", command: command("caps-log.sh") }] }],
    SubagentStop: [{ hooks: [{ type: "command", command: command("caps-log.sh") }] }],
  };
  if (cappedAgents(ast).length > 0) {
    out.PreToolUse = [{ matcher: "Agent|Task", hooks: [{ type: "command", command: command("max-subagents.sh"), onFailure: "block" }] }];
  }
  return out;
}

/** The script a timed agent's own PreToolUse hook runs, or null. */
export function timeoutScriptFor(ast: TopologyAST, agent: AgentNode): string | null {
  return timedAgents(ast).some((a) => a.id === agent.id) ? `${agent.id}-timeout.sh` : null;
}
