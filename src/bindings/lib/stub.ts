/**
 * Shared stub-script utilities for all bindings.
 *
 * A scaffold "stub" is a placeholder shell script generated when the topology
 * names a script (e.g. `gate.run: "scripts/lint.sh"`) but does not provide the
 * implementation. The user must fill it in before the topology runs for real.
 *
 * Stubs must be detectable by both humans and tools. We emit a unique marker
 * comment line — `# AGENTOPOLOGY_STUB ...` — that:
 *   - Won't appear in any user-written script unless they copied a stub.
 *   - Survives standard edits (the marker is a comment, not behavior).
 *   - Is grep-able from CI to detect un-implemented stubs.
 *
 * To detect a stub, use {@link isStubContent}. The marker is removed by the
 * user once they implement the script, which flips the file out of "stub"
 * state without any further action.
 *
 * @module
 */

/**
 * Machine-readable marker line emitted in every stub script. Detect with
 * {@link isStubContent} or grep for this exact string.
 *
 * Keep this stable — downstream tools (CI lint scripts, gate-runners, the
 * `agentopology stubs` command) match on it.
 */
export const STUB_MARKER = "# AGENTOPOLOGY_STUB — fill this in before relying on this script";

/**
 * Generate a shell script stub with a header comment and the {@link STUB_MARKER}.
 *
 * Output shape:
 *
 *   #!/usr/bin/env bash
 *   # <description>
 *   # Auto-generated by agentopology scaffold — edit as needed.
 *   # AGENTOPOLOGY_STUB — fill this in before relying on this script
 *   set -euo pipefail
 *
 *   echo "TODO: implement this script"
 *
 * The marker is the third comment line (after the description and the
 * auto-generated note) so it sits prominently at the top where a user is
 * likely to see it. Removing the marker line is the canonical way to flag the
 * script as "implemented" — `agentopology stubs` ignores files whose marker
 * has been stripped.
 */
export function shellStub(description: string, opts: { fail?: boolean } = {}): string {
  return [
    "#!/usr/bin/env bash",
    `# ${description}`,
    "# Auto-generated by agentopology scaffold — edit as needed.",
    STUB_MARKER,
    "set -euo pipefail",
    "",
    ...(opts.fail
      ? [
          // A check nobody has written must not pass: exit 2 is the code
          // Claude Code treats as "block".
          'echo "TODO: implement this script — it fails until it is written" >&2',
          "exit 2",
        ]
      // E-1: an unwritten script never reports success. Exit 1 is an error that does not block a
      // hook event (a stub on SubagentStop must not keep the agent running); a gate that runs it fails.
      : ['echo "TODO: implement this script — it fails until it is written" >&2', "exit 1"]),
    "",
  ].join("\n");
}

/**
 * A placeholder for a script a hook or gate runs, in the language of the
 * interpreter that runs it (F-24, F-25): Python for python*, JavaScript for
 * node or bun, POSIX sh for sh or dash (bash's `set -o pipefail` makes dash
 * exit 2, which blocks), bash otherwise. It carries the {@link STUB_MARKER}
 * and fails: exit 2 with `fail` (a check that must refuse), exit 1 otherwise.
 */
export function scriptStub(description: string, interpreter: string, opts: { fail?: boolean } = {}): string {
  const base = interpreter.replace(/^.*\//, "");
  const code = opts.fail ? 2 : 1;
  const msg = "TODO: implement this script — it fails until it is written";
  if (/^python/.test(base)) {
    return ["#!/usr/bin/env python3", `# ${description}`, "# Auto-generated by agentopology scaffold — edit as needed.", STUB_MARKER, "import sys", "",
      `print(${JSON.stringify(msg)}, file=sys.stderr)`, `sys.exit(${code})`, ""].join("\n");
  }
  if (base === "node" || base === "bun") {
    return ["#!/usr/bin/env node", `// ${description}`, "// Auto-generated by agentopology scaffold — edit as needed.", `// ${STUB_MARKER}`, "",
      `console.error(${JSON.stringify(msg)});`, `process.exit(${code});`, ""].join("\n");
  }
  if (base === "sh" || base === "dash" || base === "ash") {
    return ["#!/bin/sh", `# ${description}`, "# Auto-generated by agentopology scaffold — edit as needed.", STUB_MARKER, "set -eu", "",
      `echo "${msg}" >&2`, `exit ${code}`, ""].join("\n");
  }
  return shellStub(description, opts);
}

/**
 * A tool's script stub, in the tool's language (E-1). It carries the
 * {@link STUB_MARKER} and exits 1, so a gate or step that runs it before
 * anyone writes it fails instead of passing.
 */
export function toolStub(tool: { id: string; description?: string; lang?: string; args?: string[] }): string {
  const marker = tool.lang === "node" ? `// ${STUB_MARKER}` : STUB_MARKER;
  const shebang = tool.lang === "python" ? "#!/usr/bin/env python3" : tool.lang === "node" ? "#!/usr/bin/env node" : "#!/usr/bin/env bash";
  const comment = tool.lang === "node" ? "//" : "#";
  const lines = [shebang, `${comment} Tool: ${tool.id} — ${tool.description ?? ""}`, `${comment} Auto-generated by agentopology scaffold — edit as needed.`, marker, ""];
  if (tool.lang === "bash" || !tool.lang) lines.push("set -euo pipefail", "");
  if (tool.args && tool.args.length > 0) lines.push(`${comment} Args: ${tool.args.join(", ")}`, "");
  const msg = `TODO: implement ${tool.id} — it fails until it is written`;
  if (tool.lang === "python") lines.push("import sys", `print(${JSON.stringify(msg)}, file=sys.stderr)`, "sys.exit(1)");
  else if (tool.lang === "node") lines.push(`console.error(${JSON.stringify(msg)});`, "process.exit(1);");
  else lines.push(`echo ${JSON.stringify(msg)} >&2`, "exit 1");
  lines.push("");
  return lines.join("\n");
}

/**
 * Lines that make an enforcement hook script fail closed.
 *
 * Claude Code blocks only on exit 2; exit 1 (an error), 127 (a missing
 * command such as jq) or an unset variable under `set -u` let the step
 * through. An EXIT trap catches all of them, including `set -u` failures that
 * an ERR trap misses; the script sets AT_DONE=1 on its success path. Only for scripts whose job is to refuse: on a logging
 * hook, exit 2 on SubagentStop would stop the subagent from finishing.
 */
export const FAIL_CLOSED = [
  "# Fail closed: unless the script reaches its end (AT_DONE=1) or exits 2 on",
  "# purpose, it exits 2 (block). A flag, not $?: macOS bash 3.2 hands the trap",
  "# status 0 after an unset-variable error.",
  "AT_DONE=0",
  "trap 'rc=$?; if [ \"$AT_DONE\" != 1 ] && [ \"$rc\" != 2 ]; then echo \"agentopology: this check failed to run (exit $rc), so the step is blocked\" >&2; exit 2; fi' EXIT",
];

/** The last line of a fail-closed script's success path. */
export const FAIL_CLOSED_DONE = "AT_DONE=1";

/**
 * Return true if the file content contains the {@link STUB_MARKER}, indicating
 * the script is an unimplemented scaffold stub.
 *
 * Use this from CI to detect topologies that haven't been finished, or from
 * the `agentopology stubs` command to list pending work.
 */
export function isStubContent(content: string): boolean {
  return content.includes(STUB_MARKER);
}
