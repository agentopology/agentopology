/**
 * Codex permission rules: `.codex/rules/<name>.rules` (CX-13).
 *
 * The topology's `settings { allow / ask / deny }` entries of the form
 * `Bash(<command prefix> *)` become `prefix_rule(...)` calls (docs read
 * 2026-11-13). deny is `forbidden`, ask is `prompt`, allow is `allow`; Codex
 * applies the strictest matching rule. Every rule carries a `match` example
 * that the rule itself must satisfy (Codex checks it when it loads the file)
 * and, where a shorter command exists, a `not_match` example.
 *
 * Codex rules judge shell commands only. A tool name such as `WebFetch`, a
 * pattern with a wildcard inside it, or a script with redirection is not
 * expressed, and the entry is reported instead of dropped.
 *
 * @module
 */

import type { TopologyAST } from "../../parser/ast.js";
import type { GeneratedFile } from "../types.js";

export type RuleDecision = "forbidden" | "prompt" | "allow";

/** One entry turned into a rule, or the reason it could not be. */
export interface CodexRule {
  list: "deny" | "ask" | "allow";
  entry: string;
  decision: RuleDecision;
  pattern: string[];
}
export interface CodexRuleProblem {
  list: "deny" | "ask" | "allow";
  entry: string;
  message: string;
}

const DECISION: Record<"deny" | "ask" | "allow", RuleDecision> = { deny: "forbidden", ask: "prompt", allow: "allow" };
const STRICTNESS: Record<RuleDecision, number> = { allow: 0, prompt: 1, forbidden: 2 };

/** The command prefix of a `Bash(...)` entry, or a reason it has none. */
export function bashPrefix(entry: string): { pattern: string[] } | { problem: string } {
  const m = /^Bash\((.*)\)$/s.exec(entry.trim());
  if (!m) {
    return { problem: `"${entry}" is not a Bash(command) pattern; Codex rules judge shell commands only, so it has no rule` };
  }
  const words = m[1].trim().split(/\s+/).filter((w) => w !== "");
  if (words.length > 0 && (words[words.length - 1] === "*" || words[words.length - 1] === ":*")) words.pop();
  if (words.length === 0) return { problem: `"${entry}" has no command word, so it has no rule` };
  if (words.some((w) => w.includes("*") || /["'`$|&;<>()\\]/.test(w))) {
    return { problem: `"${entry}" has a wildcard or shell syntax inside the command; a Codex rule matches a command prefix only, so it has no rule` };
  }
  return { pattern: words };
}

/** Every rule the topology's settings give, strictest per pattern, and every entry that gave none. */
export function planCodexRules(ast: TopologyAST): { rules: CodexRule[]; problems: CodexRuleProblem[] } {
  const byPattern = new Map<string, CodexRule>();
  const problems: CodexRuleProblem[] = [];
  for (const list of ["deny", "ask", "allow"] as const) {
    const entries = (ast.settings?.[list] as string[] | undefined) ?? [];
    for (const entry of entries) {
      // `allow: [Read, Write, Bash]` names whole tools, not commands: nothing to write, nothing to report.
      if (list === "allow" && /^[A-Za-z][A-Za-z0-9_.*-]*$/.test(entry.trim())) continue;
      const parsed = bashPrefix(entry);
      if ("problem" in parsed) {
        problems.push({ list, entry, message: parsed.problem });
        continue;
      }
      const key = parsed.pattern.join("\u0000");
      const prior = byPattern.get(key);
      const rule: CodexRule = { list, entry, decision: DECISION[list], pattern: parsed.pattern };
      if (!prior || STRICTNESS[rule.decision] > STRICTNESS[prior.decision]) byPattern.set(key, rule);
    }
  }
  return { rules: [...byPattern.values()], problems };
}

/** A command that the pattern matches: the pattern plus example arguments. */
export function matchExample(pattern: string[]): string[] {
  const joined = pattern.join(" ");
  if (joined === "git push") return [...pattern, "origin", "main"];
  return [...pattern, "example-arg"];
}

const star = (s: string) => JSON.stringify(s);
const list = (words: string[]) => `[${words.map(star).join(", ")}]`;

/** The `.rules` text for a plan. */
export function renderRules(rules: CodexRule[], topology: string): string {
  const out = [
    `# Codex rules for ${topology} — auto-generated by agentopology scaffold.`,
    "# Codex applies the strictest matching rule. Edit settings { allow / ask / deny } in the .at, not this file.",
    "",
  ];
  for (const r of rules) {
    out.push("prefix_rule(");
    out.push(`    pattern = ${list(r.pattern)},`);
    out.push(`    decision = ${star(r.decision)},`);
    out.push(`    justification = ${star(`${topology}: ${r.list} ${r.entry}`)},`);
    out.push(`    match = [${list(matchExample(r.pattern))}],`);
    if (r.pattern.length > 1) out.push(`    not_match = [${list([r.pattern[0]])}],`);
    out.push(")", "");
  }
  return out.join("\n");
}

/** The rules file, or null when the topology gives no rule. */
export function buildCodexRules(ast: TopologyAST): { file: GeneratedFile | null; problems: CodexRuleProblem[] } {
  const { rules, problems } = planCodexRules(ast);
  if (rules.length === 0) return { file: null, problems };
  const name = ast.topology.name.replace(/[^A-Za-z0-9_-]/g, "-") || "topology";
  return { file: { path: `.codex/rules/${name}.rules`, content: renderRules(rules, ast.topology.name), category: "machine" }, problems };
}
