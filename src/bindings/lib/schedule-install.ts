/**
 * Installing a schedule: the `every:` conversions and the generated
 * scripts/install-schedule.sh that puts each job where its carrier runs it.
 */
import type { TopologyAST, ScheduleJobDef as ScheduleJob } from "../../parser/ast.js";

/**
 * A cron expression for an `every:` duration, or null when cron cannot say
 * it exactly: minutes that divide 60, hours that divide 24, days 1 to 31
 * (day-of-month steps), and the words hourly, daily and weekly.
 */
export function everyToCron(every: string): string | null {
  const text = every.trim().toLowerCase();
  const words: Record<string, string> = { hourly: "0 * * * *", daily: "0 0 * * *", weekly: "0 0 * * 0" };
  if (words[text]) return words[text];
  const m = text.match(/^(\d+)\s*(m|min|mins|minutes?|h|hours?|d|days?|w|weeks?)$/);
  if (!m) return null;
  const n = Number(m[1]);
  const unit = m[2][0];
  if (n <= 0) return null;
  if (unit === "m") return n < 60 && 60 % n === 0 ? (n === 1 ? "* * * * *" : `*/${n} * * * *`) : null;
  if (unit === "h") return n < 24 && 24 % n === 0 ? (n === 1 ? "0 * * * *" : `0 */${n} * * *`) : null;
  if (unit === "d") return n > 31 ? null : n === 1 ? "0 0 * * *" : `0 0 */${n} * *`;
  return n === 1 ? "0 0 * * 0" : null;
}

/** An `every:` duration in seconds (launchd and systemd count seconds), or null when it is not one. */
export function everySeconds(every: string): number | null {
  const text = every.trim().toLowerCase();
  const words: Record<string, number> = { hourly: 3600, daily: 86400, weekly: 604800 };
  if (words[text]) return words[text];
  const m = text.match(/^(\d+)\s*(m|min|mins|minutes?|h|hours?|d|days?|w|weeks?)$/);
  if (!m) return null;
  const n = Number(m[1]);
  if (n <= 0) return null;
  const per: Record<string, number> = { m: 60, h: 3600, d: 86400, w: 604800 };
  return n * per[m[2][0]];
}

/** A name safe in a file name and a marker comment. */
export function scheduleSlug(name: string): string {
  return name.replace(/[^A-Za-z0-9_.-]/g, "-");
}

/** The carrier a job runs on: cron unless it says otherwise. */
export const jobCarrier = (job: ScheduleJob): string => job.carrier ?? "cron";

const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/** The text of scripts/install-schedule.sh, or null when the topology has no schedule jobs. */
export function installScheduleScript(ast: TopologyAST): string | null {
  const jobs = ast.schedules ?? [];
  if (jobs.length === 0) return null;
  const name = scheduleSlug(ast.topology.name);
  const L: string[] = [
    "#!/usr/bin/env bash",
    "# Installs the schedule jobs where their carrier runs them (cron, launchd, systemd).",
    "# Auto-generated by agentopology scaffold. A dry run by default: it prints what it would do.",
    "# Pass --apply to write.",
    "set -euo pipefail",
    'ROOT="$(cd "$(dirname "$0")/.." && pwd)"',
    'APPLY=0',
    'for a in "$@"; do',
    '  case "$a" in',
    "    --apply) APPLY=1 ;;",
    '    -h|--help) echo "usage: install-schedule.sh [--apply]"; exit 0 ;;',
    '    *) echo "unknown argument: $a" >&2; exit 2 ;;',
    "  esac",
    "done",
    'HOST="${FAKE_HOSTNAME:-$(hostname)}"',
    'HOST_SHORT="${HOST%%.*}"',
    "",
    "# A job that names a machine installs only on it.",
    "machine_ok() {",
    '  [ "$1" = "$HOST" ] || [ "$1" = "$HOST_SHORT" ]',
    "}",
    "wrong=0",
  ];
  const known = new Set(["cron", "launchd", "systemd"]);
  const enabled = jobs.filter((j) => j.enabled !== false);
  for (const j of enabled) {
    if (j.machine && known.has(jobCarrier(j))) {
      L.push(`machine_ok ${q(j.machine)} || { echo "job ${j.id} is for machine ${j.machine}, this is $HOST: nothing installed" >&2; wrong=1; }`);
    }
  }
  L.push('[ "$wrong" = 0 ] || exit 1', "");
  L.push('if [ "$APPLY" = 1 ]; then echo "applying"; else echo "dry run: nothing is written (pass --apply to install)"; fi', "");

  // cron: one block, replaced as a whole
  const cronJobs = enabled.filter((j) => jobCarrier(j) === "cron");
  if (cronJobs.length > 0) {
    L.push(`BEGIN_MARK="# BEGIN agentopology ${name}"`, `END_MARK="# END agentopology ${name}"`, "BLOCK=\"$BEGIN_MARK\"");
    for (const j of cronJobs) {
      const expr = j.cron ?? (j.every ? everyToCron(j.every) : null);
      if (!expr) {
        L.push(`echo "job ${j.id}: no cron expression (every: ${j.every ?? "unset"}); skipped" >&2`);
        continue;
      }
      L.push(`BLOCK="$BLOCK"$'\\n'"${expr} cd '$ROOT' && bash scripts/schedule-${j.id}.sh  # ${j.id}"`);
    }
    L.push(
      'BLOCK="$BLOCK"$\'\\n\'"$END_MARK"',
      'echo "cron: crontab block for ' + name + ':"',
      'echo "$BLOCK" | sed "s/^/  /"',
      'if [ "$APPLY" = 1 ]; then',
      '  CURRENT="$(crontab -l 2>/dev/null || true)"',
      '  KEPT="$(printf \'%s\\n\' "$CURRENT" | awk -v b="$BEGIN_MARK" -v e="$END_MARK" \'$0==b{skip=1;next} $0==e{skip=0;next} !skip\')"',
      '  if [ -n "$(printf \'%s\' "$KEPT" | tr -d \'[:space:]\')" ]; then NEW="$KEPT"$\'\\n\'"$BLOCK"; else NEW="$BLOCK"; fi',
      '  printf \'%s\\n\' "$NEW" | crontab -',
      '  echo "cron: installed"',
      "fi",
      "",
    );
  }

  // launchd: one plist per job
  for (const j of enabled.filter((x) => jobCarrier(x) === "launchd")) {
    const secs = j.every ? everySeconds(j.every) : null;
    if (!secs) {
      L.push(`echo "job ${j.id}: launchd needs every: \\"<N>m\\", \\"<N>h\\" or \\"<N>d\\"; skipped" >&2`, "");
      continue;
    }
    const label = `agentopology.${name}.${j.id}`;
    const runAtLoad = j.survives === "reboot" ? "true" : "false";
    L.push(
      `PLIST="$HOME/Library/LaunchAgents/${label}.plist"`,
      `echo "launchd: $PLIST (every ${secs}s, RunAtLoad ${runAtLoad})"`,
      'if [ "$APPLY" = 1 ]; then',
      '  mkdir -p "$HOME/Library/LaunchAgents"',
      '  cat > "$PLIST" <<PLIST_EOF',
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
      "<plist version=\"1.0\">",
      "<dict>",
      "  <key>Label</key>",
      `  <string>${label}</string>`,
      "  <key>ProgramArguments</key>",
      "  <array>",
      "    <string>/bin/bash</string>",
      `    <string>$ROOT/scripts/schedule-${j.id}.sh</string>`,
      "  </array>",
      "  <key>WorkingDirectory</key>",
      "  <string>$ROOT</string>",
      "  <key>StartInterval</key>",
      `  <integer>${secs}</integer>`,
      "  <key>RunAtLoad</key>",
      `  <${runAtLoad}/>`,
      "</dict>",
      "</plist>",
      "PLIST_EOF",
      '  if command -v launchctl >/dev/null 2>&1; then launchctl unload "$PLIST" 2>/dev/null || true; launchctl load -w "$PLIST" || true; fi',
      '  echo "launchd: installed"',
      "fi",
      "",
    );
  }

  // systemd: a user service and timer per job
  for (const j of enabled.filter((x) => jobCarrier(x) === "systemd")) {
    const secs = j.every ? everySeconds(j.every) : null;
    if (!secs) {
      L.push(`echo "job ${j.id}: systemd needs every: \\"<N>m\\", \\"<N>h\\" or \\"<N>d\\"; skipped" >&2`, "");
      continue;
    }
    const unit = `agentopology-${name}-${j.id}`;
    L.push(
      `UNIT_DIR="$HOME/.config/systemd/user"`,
      `echo "systemd: $UNIT_DIR/${unit}.service and .timer (every ${secs}s${j.survives === "reboot" ? ", Persistent=true" : ""})"`,
      'if [ "$APPLY" = 1 ]; then',
      '  mkdir -p "$UNIT_DIR"',
      `  cat > "$UNIT_DIR/${unit}.service" <<UNIT_EOF`,
      "[Unit]",
      `Description=agentopology ${name} job ${j.id}`,
      "",
      "[Service]",
      "Type=oneshot",
      "WorkingDirectory=$ROOT",
      `ExecStart=/bin/bash $ROOT/scripts/schedule-${j.id}.sh`,
      "UNIT_EOF",
      `  cat > "$UNIT_DIR/${unit}.timer" <<UNIT_EOF`,
      "[Unit]",
      `Description=agentopology ${name} job ${j.id} timer`,
      "",
      "[Timer]",
      `OnBootSec=${secs}s`,
      `OnUnitActiveSec=${secs}s`,
      ...(j.survives === "reboot" ? ["Persistent=true"] : []),
      "",
      "[Install]",
      "WantedBy=timers.target",
      "UNIT_EOF",
      `  if command -v systemctl >/dev/null 2>&1; then systemctl --user daemon-reload || true; systemctl --user enable --now ${unit}.timer || true; fi`,
      '  echo "systemd: installed"',
      "fi",
      "",
    );
  }

  // everything else is somebody else's to start
  for (const j of enabled.filter((x) => !known.has(jobCarrier(x)))) {
    L.push(`echo "job ${j.id}: carrier ${jobCarrier(j)} is set up outside this script; nothing to install"`);
  }
  for (const j of jobs.filter((x) => x.enabled === false)) L.push(`echo "job ${j.id}: disabled; skipped"`);
  L.push("");
  return L.join("\n");
}
