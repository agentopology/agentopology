/**
 * Run controls the person holds (0.13.1, Claude Code): the stop word, the wall-time cap, the egress gate.
 *
 * - go-halt.sh (S-201): PreToolUse on every tool. Refuses while the last row of a human with a `stop-word:` in
 *   its go ledger is a halt row, the row the go hook writes from a typed stop word.
 *
 * Every script here fails closed (an exit 2 unless it reaches its end) and is written only when the topology
 * uses its field, so a topology that does not use them generates the same files as before.
 *
 * @module
 */

import type { AgentNode, TopologyAST } from "../../parser/ast.js";
import { goLedgers } from "../../parser/ledger.js";
import type { GeneratedFile } from "../types.js";
import { durationSeconds, goHumans, projectRootLines, shellQuote, type GuardPlatform } from "./guards.js";
import { FAIL_CLOSED, FAIL_CLOSED_DONE } from "./stub.js";

const NEED_JQ = (what: string) =>
  `command -v jq >/dev/null 2>&1 || { echo "agentopology: jq is required ${what}, so the call is blocked. Install jq." >&2; exit 2; }`;

export const WALL_START_SCRIPT = "wall-start.sh";
export const WALL_TIME_SCRIPT = "wall-time.sh";

/** The entry agent's wall-time cap as written and in seconds, or null when none (or not a duration). */
export function wallCap(ast: TopologyAST): { raw: string; secs: number; agent: string } | null {
  const id = ast.topology.entry;
  const a = ast.nodes.find((n) => n.type === "agent" && n.id === id) as AgentNode | undefined;
  const secs = durationSeconds(a?.wallTime);
  return a && a.wallTime !== undefined && secs !== null && secs > 0 ? { raw: a.wallTime, secs, agent: a.id } : null;
}

/** wall-start.sh (SessionStart) and wall-time.sh (PreToolUse, every tool). Empty when the entry agent has no wall-time. */
export function generateWallScripts(ast: TopologyAST, p: GuardPlatform): GeneratedFile[] {
  const cap = wallCap(ast);
  if (!cap) return [];
  const name = ast.topology.name;
  const dir = `${p.stateDir}/wall-time`;
  const sid = [
    `SID=$(printf '%s' "$INPUT" | jq -er '.session_id | strings') || SID=''`,
    `case "$SID" in ''|*[!A-Za-z0-9_-]*) SID='' ;; esac`,
  ];
  const start = [
    "#!/usr/bin/env bash",
    `# Wall-time start for topology "${name}": records when the session began, for ${WALL_TIME_SCRIPT}.`,
    "# Auto-generated by agentopology scaffold. SessionStart hook. It never blocks (exit 0).",
    `# One file per session in ${dir}/, written once: a resume or a compact of the same session`,
    "# keeps the first start, and another session (a nested claude run) has its own clock.",
    "set -u",
    '[ -n "${CLAUDE_PROJECT_DIR:-}" ] && cd "$CLAUDE_PROJECT_DIR" 2>/dev/null',
    "INPUT=$(cat)",
    'command -v jq >/dev/null 2>&1 || { echo "agentopology: jq is not installed, so the wall-time start is not recorded and the cap will refuse every tool" >&2; exit 0; }',
    ...sid,
    '[ -n "$SID" ] || { echo "agentopology: the hook input has no usable session_id, so the wall-time start is not recorded" >&2; exit 0; }',
    `if [ -L ${p.stateDir} ] || [ -L ${dir} ]; then echo "agentopology: ${dir} or its folder is a symlink; not recording the start" >&2; exit 0; fi`,
    `mkdir -p ${dir} || exit 0`,
    `F=${dir}/$SID`,
    '[ -e "$F" ] && exit 0',
    'NOW=$(date +%s)',
    '[ "${AGENTOPOLOGY_TEST:-}" = 1 ] && [ -n "${AT_NOW:-}" ] && NOW=$AT_NOW',
    'printf \'%s\\n\' "$NOW" > "$F"',
    "exit 0",
    "",
  ];
  const guard = [
    "#!/usr/bin/env bash",
    `# Wall-time for topology "${name}" (entry agent "${cap.agent}", wall-time: ${cap.raw}): refuses every tool call once`,
    `# the session has run longer than ${cap.raw} since its SessionStart. Auto-generated by agentopology scaffold.`,
    "# PreToolUse hook on every tool; exit 2 blocks. A subagent's call counts: the cap is the session's.",
    `# The start is read from ${dir}/<session_id>, written by ${WALL_START_SCRIPT}. No start recorded (the file is`,
    "# gone, the hook did not run, jq is missing) refuses: a cap that cannot be read does not open.",
    "# Text check of elapsed time between calls: it does not interrupt a call already running.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...projectRootLines(p, name, "fallback"),
    NEED_JQ("to check the wall-time cap"),
    "INPUT=$(cat)",
    ...sid,
    `[ -n "$SID" ] || { echo "agentopology: wall-time: the call has no usable session_id, so the ${cap.raw} cap cannot be checked and the call is blocked" >&2; exit 2; }`,
    `F=${dir}/$SID`,
    `[ -f "$F" ] || { echo "agentopology: wall-time: no start was recorded for this session, so the ${cap.raw} cap cannot be checked and the call is blocked. Restart the session so the SessionStart hook runs." >&2; exit 2; }`,
    'START=$(head -n 1 "$F" 2>/dev/null) || START=""',
    `case "$START" in ''|*[!0-9]*) echo "agentopology: wall-time: the start time recorded for this session is not a number, so the ${cap.raw} cap cannot be checked and the call is blocked" >&2; exit 2 ;; esac`,
    "NOW=$(date +%s)",
    '[ "${AGENTOPOLOGY_TEST:-}" = 1 ] && [ -n "${AT_NOW:-}" ] && NOW=$AT_NOW',
    "ELAPSED=$((NOW - START))",
    `if [ "$ELAPSED" -gt ${cap.secs} ]; then`,
    `  echo "agentopology: wall-time: this session passed its cap of ${cap.raw} (\${ELAPSED}s since it started), so every tool call is refused. Stop and report what you have." >&2`,
    "  exit 2",
    "fi",
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  const d = p.scriptsDir(name);
  return [
    { path: `${d}/${WALL_START_SCRIPT}`, content: start.join("\n"), category: "script", executable: true },
    { path: `${d}/${WALL_TIME_SCRIPT}`, content: guard.join("\n"), category: "script", executable: true },
  ];
}

/** Humans whose go hook is written and that have a stop word. */
export function stopHumans(ast: TopologyAST, p: GuardPlatform) {
  return goHumans(ast, p).filter((h) => h.stopWord !== undefined && h.stopWord.trim() !== "");
}

export const HALT_SCRIPT = "go-halt.sh";

/** go-halt.sh: refuse every tool while a human's last go-ledger row is a halt. Null when no human has a stop word. */
export function generateHaltScript(ast: TopologyAST, p: GuardPlatform): GeneratedFile | null {
  const humans = stopHumans(ast, p);
  if (humans.length === 0) return null;
  const name = ast.topology.name;
  const sq = shellQuote;
  const checks = humans.flatMap((h) =>
    goLedgers(ast, h.id).map((r) => r.path.replace(/^\.\//, "")).flatMap((l) => [
      `halted ${sq(l)} ${sq(h.id)} || {`,
      `  echo ${sq(`agentopology: halted: the person typed the stop word "${h.stopWord!.trim()}" (${h.id}), so every tool call is refused. Stop and wait; the person types the go word "${h.word!.trim()}" to continue.`)} >&2`,
      "  exit 2",
      "}",
    ]));
  const lines = [
    "#!/usr/bin/env bash",
    `# The stop word of topology "${name}": refuses every tool call while the last row of a human with a`,
    `# stop-word: (${humans.map((h) => h.id).join(", ")}) in its go ledger is a halt row, {step, ok: false, halt: true, word, ts}.`,
    `# Auto-generated by agentopology scaffold. PreToolUse hook on every tool; exit 2 blocks.`,
    "# The halt row is written by the go hook (UserPromptSubmit) from a prompt the person typed. The go word,",
    "# typed, writes the next row and ends the halt. This script never blocks a prompt, only a tool call.",
    "# A ledger that cannot be read refuses (a missing ledger holds no halt). Text check: it reads the ledger;",
    "# it does not stop a process already running, and a tool call is refused only when the host runs this hook.",
    "set -euo pipefail",
    ...FAIL_CLOSED,
    ...projectRootLines(p, name, "fallback"),
    NEED_JQ("to read the go ledger"),
    "cat >/dev/null",
    "halted() { # LEDGER STEP: returns 1 when the last row of STEP is a halt",
    '  [ -f "$1" ] || return 0',
    "  local last",
    `  last=$(jq -rs --arg s "$2" '[.[] | select(type == "object" and .step == $s)] | last | if . != null and .halt == true then "halt" else "go" end' "$1" 2>/dev/null) || { echo "agentopology: the go ledger $1 could not be read, so the call is blocked" >&2; exit 2; }`,
    '  [ "$last" != halt ]',
    "}",
    ...checks,
    FAIL_CLOSED_DONE,
    "exit 0",
    "",
  ];
  return { path: `${p.scriptsDir(name)}/${HALT_SCRIPT}`, content: lines.join("\n"), category: "script", executable: true };
}
