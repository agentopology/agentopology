#!/usr/bin/env node
/**
 * Have Claude Code's documented keys moved since the schema was last checked?
 *
 *   node scripts/claude-code-schema-drift.mjs                   fetch the pages, diff them with the schema, exit 1 on drift
 *   node scripts/claude-code-schema-drift.mjs --from-dir <dir>  read saved copies instead (<dir>/settings-reference.md, sub-agents.md, skills.md)
 *   node scripts/claude-code-schema-drift.mjs --write           regenerate src/bindings/claude-code-settings-keys.ts from the settings page
 *
 * A key whose Scope is `Global config` lives in ~/.claude.json, not in a
 * settings file: it goes to GLOBAL_CONFIG_KEYS, never to the settings rows.
 *
 * Frontmatter rows (src/bindings/claude-code-schema.ts) are edited by hand
 * from the printed list. Needs `npm run build`.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { extractSettingsKeys, extractFrontmatterKeys } from "../dist/conformance/extract-schema.js";

const BASE = "https://code.claude.com/docs/en/";
const PAGES = { settings: "settings-reference.md", agent: "sub-agents.md", skill: "skills.md" };
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generated = path.join(root, "src/bindings/claude-code-settings-keys.ts");

const argv = process.argv.slice(2);
const opt = (name) => { const i = argv.indexOf(name); return i === -1 ? undefined : argv[i + 1]; };
const fromDir = opt("--from-dir");
const read = async (file) => fromDir ? fs.readFileSync(path.join(fromDir, file), "utf8") : await (await fetch(BASE + file)).text();

const documented = extractSettingsKeys(await read(PAGES.settings));
const settings = documented.filter((k) => !k.globalConfig);
const globalConfig = documented.filter((k) => k.globalConfig);
if (settings.length === 0) {
  console.error("No settings keys found on the page: its layout changed. Re-check src/conformance/extract-schema.ts.");
  process.exit(2);
}

if (argv.includes("--write")) {
  const date = new Date().toISOString().slice(0, 10);
  const body = (keys) => keys.map((k) => `  ${JSON.stringify(k)},`).join("\n");
  fs.writeFileSync(generated, `// Generated by scripts/claude-code-schema-drift.mjs --write from ${BASE}${PAGES.settings}.
// Do not edit by hand: rerun the script, then review the diff.
import type { DocSettingsKey } from "../conformance/extract-schema.js";

/** The date the settings reference page was read. */
export const SETTINGS_DOC_DATE = "${date}";

/** Every key the settings reference documents with a type, for a settings file. */
export const SETTINGS_KEYS: readonly DocSettingsKey[] = [
${body(settings)}
];

/** Keys whose Scope is Global config: they live in ~/.claude.json, and no binding writes them. */
export const GLOBAL_CONFIG_KEYS: readonly DocSettingsKey[] = [
${body(globalConfig)}
];
`);
  console.log(`wrote ${path.relative(root, generated)} (${settings.length} settings keys, ${globalConfig.length} global-config keys)`);
  process.exit(0);
}

const { ccKeys } = await import("../dist/bindings/claude-code-schema.js");
const lines = [];
for (const [surface, keys] of [["settings", settings], ["global-config", globalConfig]]) {
  const have = new Map(ccKeys(surface).map((r) => [r.key, r]));
  for (const k of keys) {
    const row = have.get(k.key);
    if (!row) { lines.push(`${surface} + ${k.key} (${k.type})`); continue; }
    if (row.type !== k.type || JSON.stringify(row.values ?? null) !== JSON.stringify(k.values ?? null) || row.projectFile !== k.projectFile)
      lines.push(`${surface} ~ ${k.key}: ${row.type} ${JSON.stringify(row.values ?? [])} project=${row.projectFile} → ${k.type} ${JSON.stringify(k.values ?? [])} project=${k.projectFile}`);
    if ((row.removed ?? null) !== (k.removed ?? null)) lines.push(`${surface} ~ ${k.key}: removed ${JSON.stringify(row.removed ?? null)} → ${JSON.stringify(k.removed ?? null)}`);
    if ((row.deprecated ?? null) !== (k.deprecated ?? null)) lines.push(`${surface} ~ ${k.key}: deprecated ${JSON.stringify(row.deprecated ?? null)} → ${JSON.stringify(k.deprecated ?? null)}`);
  }
  for (const key of have.keys()) if (!keys.some((k) => k.key === key)) lines.push(`${surface} - ${key}`);
}

for (const surface of ["agent", "skill"]) {
  const doc = extractFrontmatterKeys(await read(PAGES[surface]));
  const rows = ccKeys(surface).map((r) => r.key);
  for (const k of doc) if (!rows.includes(k)) lines.push(`${surface} + ${k}`);
  for (const k of rows) if (!doc.includes(k)) lines.push(`${surface} - ${k}`);
}

console.log(`Claude Code schema vs ${fromDir ?? BASE}: ${lines.length === 0 ? "no drift" : `${lines.length} change(s)`}`);
for (const l of lines) console.log(`  ${l}`);
process.exit(lines.length === 0 ? 0 : 1);
